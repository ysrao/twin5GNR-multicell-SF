"""MCS audit mode: is the gNB's link adaptation doing what the
twin says it should?

The twin derives, for every receiver, the reference MCS -- the
highest MCS whose Sionna SYS PHYAbstraction decode threshold the
receiver's SINR meets. That is what link adaptation *should*
sustain. The gNB's actual behaviour is observable in PM counters as
the per-sector MCS distribution of scheduled grants, and is
modelled as a rule: the gNB picks the highest MCS decoding at
(SINR + olla_offset), subject to an MCS cap. A negative offset is a
conservative gNB (throughput left on the table); a positive one is
an aggressive gNB (first transmissions the PHY says will fail).

The audit estimates the gNB's effective offset (and whether the
cap binds) by matching the modelled MCS histogram to the PM
histogram, then proposes the correction -- shift the OLLA offset
toward zero, raise a binding cap -- only if the twin verifies the
gain first (guarded acceptance, as everywhere in this package):
the estimated offset must exceed the action threshold, the
correction step is capped, and the twin-modelled spectral
efficiency after correction must beat the current rule by the
required margin.

SE accounting: a grant at MCS m delivers bits_per_re[m] (from the
SYS calibration) when m is decodable at the receiver's SINR; a
grant above the reference MCS fails its first transmission and is
modelled as one HARQ retransmission at the reference MCS, i.e.
half the reference rate over the two slots.
"""
import numpy as np

import twin as twin_mod

ACTION_THRESHOLD_DB = 1.0     # ignore offsets smaller than this
MAX_CORRECTION_DB = 4.0       # bounded step per audit cycle
MIN_SE_GAIN = 0.02            # required relative SE gain to act
CAP_BINDING_SHARE = 0.05      # twin MCS above cap for >5% = binding


def receiver_sinr(scorer, config):
    """Per-receiver best-server SINR (dB) and serving sector under a
    configuration, from the twin scorer's machinery."""
    R = scorer.sector_rsrp(config)
    flat = np.where(np.isnan(R), -np.inf, R)
    serving = flat.argmax(axis=1)
    have = np.isfinite(flat.max(axis=1))
    p_lin = 10 ** (flat / 10.0)
    p_best = p_lin[np.arange(len(R)), serving]
    p_int = p_lin.sum(axis=1) - p_best
    noise = 10 ** (twin_mod.NOISE_PER_RE_DBM / 10.0)
    sinr = 10 * np.log10(np.maximum(p_best, 1e-300) / (p_int + noise))
    return np.where(have, sinr, np.nan), serving, have


def reference_mcs(scorer, sinr_db):
    """Highest MCS whose PHY decode threshold the SINR meets;
    -1 where no MCS decodes."""
    idx = np.searchsorted(scorer.thresholds, sinr_db, side="right") - 1
    return idx  # -1 .. 27


def rule_mcs(scorer, sinr_db, olla_offset_db, mcs_cap):
    """The gNB's modelled MCS rule at effective SINR + offset."""
    m = reference_mcs(scorer, sinr_db + olla_offset_db)
    return np.minimum(m, mcs_cap)


def histogram(mcs_values, weights=None):
    """Normalised MCS histogram over 0..27 (undeliverable -1 grants
    are excluded -- they carry no grant in PM either)."""
    v = np.asarray(mcs_values)
    ok = v >= 0
    if weights is None:
        w = np.ones(len(v))
    else:
        w = np.asarray(weights, dtype=float)
    h = np.zeros(28)
    np.add.at(h, v[ok], w[ok])
    return h / max(h.sum(), 1e-9)


def expected_se(scorer, sinr_db, mcs_values):
    """Mean delivered bits/RE under an MCS assignment, with the
    HARQ penalty for grants above the reference MCS."""
    ref = reference_mcs(scorer, sinr_db)
    m = np.asarray(mcs_values)
    bits = scorer.bits_per_re
    se = np.zeros(len(m))
    ok = (m >= 0) & (ref >= 0)
    good = ok & (m <= ref)
    over = ok & (m > ref)
    se[good] = bits[m[good]]
    se[over] = 0.5 * bits[ref[over]]
    return float(se.mean()), {
        "over_reach_share": float(np.mean(over)),
        "undeliverable_share": float(np.mean(ref < 0)),
    }


def estimate_offset(scorer, sinr_db, pm_hist, mcs_cap,
                    grid=np.arange(-8.0, 4.01, 0.25)):
    """Grid-search the OLLA offset whose modelled MCS histogram
    best matches the PM histogram (L1 distance)."""
    best = (None, np.inf)
    for d in grid:
        h = histogram(rule_mcs(scorer, sinr_db, d, mcs_cap))
        dist = float(np.abs(h - pm_hist).sum())
        if dist < best[1]:
            best = (float(d), dist)
    return best  # (offset_db, l1_distance)


def simulate_pm(scorer, sinr_db, serving, olla_offset_db, mcs_cap,
                grants_per_sector=20_000, seed=7):
    """Stand-in PM file: per-sector MCS histograms generated by
    applying the true gNB rule to the twin's receivers and sampling
    grants. In deployment this file is replaced by real PM exports;
    the schema is the contract."""
    rng = np.random.default_rng(seed)
    out = {}
    for s in range(3):
        m = serving == s
        if not m.any():
            out[str(s)] = [0.0] * 28
            continue
        per_rx = rule_mcs(scorer, sinr_db[m], olla_offset_db, mcs_cap)
        ok = per_rx >= 0
        draws = rng.choice(per_rx[ok], size=grants_per_sector,
                           replace=True)
        out[str(s)] = histogram(draws).tolist()
    return out


def audit_sector(scorer, sinr_db, pm_hist, configured_offset, mcs_cap):
    """Full audit of one sector's receiver SINRs against its PM
    histogram. The histogram match estimates the gNB's EFFECTIVE
    offset (how it actually behaves relative to the twin's SINR);
    the correction adjusts the CONFIGURED offset by the negative
    of that estimate, bounded, so the effective behaviour lands
    where the configuration intends. Returns finding + correction."""
    ref = reference_mcs(scorer, sinr_db)
    est_offset, l1 = estimate_offset(scorer, sinr_db, pm_hist, mcs_cap)
    cap_share = float(np.mean(ref > mcs_cap))
    cap_binding = cap_share > CAP_BINDING_SHARE

    se_twin, _ = expected_se(scorer, sinr_db, ref)
    se_now, diag_now = expected_se(
        scorer, sinr_db, rule_mcs(scorer, sinr_db, est_offset, mcs_cap))

    step = float(np.clip(-est_offset, -MAX_CORRECTION_DB, MAX_CORRECTION_DB))
    new_effective = est_offset + step
    new_cap = 27 if cap_binding else mcs_cap
    se_fixed, diag_fixed = expected_se(
        scorer, sinr_db, rule_mcs(scorer, sinr_db, new_effective, new_cap))
    gain = (se_fixed - se_now) / max(se_now, 1e-9)

    act = (abs(est_offset) >= ACTION_THRESHOLD_DB
           and gain >= MIN_SE_GAIN)
    return {
        "receivers": int(len(sinr_db)),
        "twin_mean_mcs": float(np.mean(ref[ref >= 0])),
        "pm_mean_mcs": float((pm_hist * np.arange(28)).sum()),
        "estimated_effective_offset_db": est_offset,
        "histogram_l1_distance": l1,
        "cap_binding": bool(cap_binding),
        "cap_binding_share": cap_share,
        "se_twin_bits_per_re": se_twin,
        "se_current_rule_bits_per_re": se_now,
        "se_after_correction_bits_per_re": se_fixed,
        "se_gain_relative": float(gain),
        "over_reach_share_current": diag_now["over_reach_share"],
        "over_reach_share_after": diag_fixed["over_reach_share"],
        "recommendation": (
            {"olla_offset_adjustment_db": step,
             "new_configured_offset_db": float(configured_offset + step),
             "mcs_cap": new_cap}
            if act else None),
        "provenance": ("mcs_audit_guarded_accept" if act
                       else "mcs_audit_no_action_within_tolerance"),
    }
